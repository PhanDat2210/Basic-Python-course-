# Lý thuyết 02.B - Kiểu dữ liệu (Data type)

x = 10  # int - integer
y = 10.5  # float - floating point
z = "Hello"  # str - string
b = False  # bool - boolean
li = [1, 2, 3, "Python", True]  # list

print(x)  # In ra 10
print(y)  # In ra 10.5
print(z)  # In ra Hello
print(b)  # In ra False
print(li)  # In ra [1,2,3'Python',True]
print(type(x))  # In ra <class 'int'>    type(x)     #In ra <class 'int'>
