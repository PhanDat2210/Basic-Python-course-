# Phép cộng trừ nhân chia: + - * / // %
# Phép tự tăng, tự giảm
# Phép toán nâng cao: căn (sqrt), mũ (**), trị tuyệt đối (abs)
x = 1 + 2
y = x - 1
z = x * y + 1
u1 = z / 2
u2 = z // 2  # lấy phần nguyen
u3 = z % 2  # nguyên
import math

print(u1)
print(u2)
print(u3)

x = 9
abs(x**3)
math.sqrt(x)
print(x**2)  # mũ
print(abs(x**3))  # giá trị tuyệt đối
print(math.sqrt(x))  # căn

